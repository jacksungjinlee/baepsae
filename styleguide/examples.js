// "{name}" 자리를 채워요. 없는 자리는 그대로 두어 눈에 띄게 해요.
export function fill(tpl, vars) {
  return tpl.replace(/\{(\w+)\}/g, (m, k) => (vars && vars[k] != null ? String(vars[k]) : m));
}
